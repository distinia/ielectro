            <p class="paragraph"><b class="bold">Somalia</b>, officially the <b class="bold">Somali Democratic
                    Republic</b>, is a <b class="bold">unitary presidential republic</b> located in the Horn of Africa,
                established after the peaceful unification of <b class="bold">Greater Somalia</b>. It represents a <b class="bold">new political era</b> for the Somali people, founded on the principles of <b class="bold">totalitarian democracy</b>, national unity, and centralized governance. The state
                officially proclaims <b class="bold">Islam as the state religion</b>, while guaranteeing cultural
                continuity
                and national sovereignty.
            </p>
            <p class="paragraph">The <b class="bold">capital city</b> is <b class="bold">yet to be officially
                    designated</b>,
                pending constitutional ratification. <b class="bold">Somali</b> is recognized as the <b class="bold">sole
                    official language</b>, reinforcing national cohesion. The population is composed of approximately <b class="bold">85% ethnic Somali</b> and <b class="bold">15% minority groups</b>, all united under a
                shared national identity. Citizens are referred to as <b class="bold">Somalis</b>.</p>
            <p class="paragraph">The Somali Democratic Republic operates under a <b class="bold">presidential
                    system</b>,
                led by
                a <b class="bold">President</b> serving as both <b class="bold">head of state and government</b>,
                alongside
                a <b class="bold">Prime Minister</b> responsible for executive coordination. Both positions are <b class="bold">yet to be formally appointed</b> under the new constitutional framework. Legislative
                power
                is vested in the <b class="bold">National Parliament</b>, a <b class="bold">bicameral body</b>
                consisting of
                the <b class="bold">Senate (Upper House)</b> and the <b class="bold">House of the People (Lower
                    House)</b>.
                This structure aims to balance regional representation with popular sovereignty.</p>
            <p class="paragraph">The country&rsquo;s <b class="bold">currency</b> is the <b class="bold">Somali
                    shilling</b>,
                reaffirming economic continuity while pursuing monetary reform. Key national statistics, including <b class="bold">population size, territorial area, GDP, and constitutional adoption date</b>, remain <b class="bold">to be officially defined</b> as part of the transitional state-building process.
            </p>
            <p class="paragraph">The Somali Democratic Republic officially <b class="bold">succeeded the Federal
                    Republic of
                    Somalia</b>, marking a historic transformation from a federal system to a <b class="bold">centralized
                    unitary state</b>, designed to strengthen national authority, restore public order, and ensure
                long-term
                stability.</p>
