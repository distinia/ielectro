                solar projects in the southern mesas.
            </p>
            <p class="paragraph">The industrial base is centered around <b class="bold">mining, heavy machinery,
                    chemical
                    processing, and basic manufacturing</b>, often geared toward domestic consumption rather than
                export.
                Unlike many major economies, <b class="bold">Fesia exports relatively little</b>, focusing instead on
                raw
                resource extraction and internal market development. Some value-added sectors are
                emerging&mdash;especially
                in construction materials and electronics components&mdash;but these remain secondary in global trade
                terms.
            </p>
            <p class="paragraph">Fesia&rsquo;s economy is heavily influenced by state policy, with <b class="bold">strategic
                    sectors under public control or close government regulation</b>. Infrastructure spending, mineral
                concessions, and foreign investment deals are tightly coordinated by central authorities to protect
                national
                interests and promote long-term sovereignty. The private sector, while active, operates within a
                framework
