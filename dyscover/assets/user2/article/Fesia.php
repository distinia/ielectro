            </p>
            <p class="paragraph">Unemployment remains low, and the government supports a <b class="bold">strong public
                    sector,
                    state-led development programs, and welfare safety nets</b>, particularly in health and education.
                However, economic planners continue to warn of vulnerabilities tied to <b class="bold">import
                    dependence,
                    commodity price volatility, and regional inequality</b>. As the country deepens its integration into
                continental markets and pursues a vision of self-sufficiency, the long-term challenge will be to <b class="bold">transform its natural wealth into sustainable industrial power</b>, reduce its reliance
                on
                foreign food and fuel, and position itself not just as a resource supplier&mdash;but as a fully
                developed
                economic player.
            </p>
