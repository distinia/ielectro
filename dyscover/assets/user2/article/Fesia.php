                loyalty to the <b class="bold">republic&rsquo;s institutions</b> and adherence to the <b class="bold">Constitution</b>.</p>
            <p class="paragraph">The <b class="bold">military doctrine</b> of Fesia is founded on <b class="bold">defensive
                    self-reliance</b>, <b class="bold">regional deterrence</b>, and <b class="bold">international
                    cooperation</b>. Strategically, the country maintains close defense partnerships with <b class="bold">Suklan</b>, <b class="bold">Cusea</b>, and <b class="bold">Destenia</b>, engaging in
