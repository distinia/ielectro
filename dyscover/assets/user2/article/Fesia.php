            <p class="paragraph">Fesia possesses the <b class="bold">9th-largest economy in the world</b>, with a Gross
                Domestic
                Product of <b class="bold">850 billion DTR</b>, reflecting a complex and resource-rich system that is
                still
                maturing in terms of industrial diversification and trade balance. The country's economic foundation
                rests
                on <b class="bold">abundant underground resources and mineral wealth</b>, making Fesia the <b class="bold">leading global producer of raw minerals</b>, particularly rare earth elements, copper,
                iron, and industrial metals. These are found beneath its vast <b class="bold">mesa biome</b>, a unique
                geographic landscape that, while agriculturally limited, holds <b class="bold">immense geological
                    value</b>.
            </p>
            <p class="paragraph">Despite this mineral dominance, Fesia faces structural vulnerabilities, especially in
                the
                <b class="bold">agricultural sector</b>, due to the <b class="bold">arid and plateau-based
                    environment</b>
                of most of its territory. The mesa terrain offers limited arable land and irregular water availability,
                leading to a <b class="bold">heavy reliance on food imports</b>, particularly grains, vegetables, and
                livestock feed. The government has invested in irrigation technologies and greenhouse farming to offset
                this
                dependence, but results have been modest. As a consequence, Fesia maintains <b class="bold">a trade
                    deficit
                    in agriculture</b>, relying heavily on foreign markets for nutritional security.
            </p>
            <p class="paragraph">Fesia also <b class="bold">imports a significant portion of its energy needs</b>,
                particularly
