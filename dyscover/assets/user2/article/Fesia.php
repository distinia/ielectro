                through long-term bilateral agreements. The country possesses <b class="bold">modest natural gas
                    reserves</b>, enough to cover basic domestic use, but not sufficient for industrial or
                transportation-scale demand. This makes energy security a recurring topic in economic planning and
                foreign
                policy, driving efforts to diversify suppliers and gradually develop renewable alternatives,
